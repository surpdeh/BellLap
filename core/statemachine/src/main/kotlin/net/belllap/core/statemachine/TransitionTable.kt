package net.belllap.core.statemachine

/** Generates the markdown transition table committed as docs/state-machine.md. */
object TransitionTable {
    val states: List<State> =
        listOf(
            State.Setup,
            State.Standby,
            State.Arming,
            State.Armed,
            State.Acquisition(flagVisible = true),
            State.Acquisition(flagVisible = false),
            State.Review(State.Setup),
            State.Review(State.Standby),
            State.Review(State.Armed),
        )

    val events: List<Event> =
        listOf(
            Event.StandbyRequested,
            Event.BellDetected,
            Event.BellNow,
            Event.ArmDelayElapsed,
            Event.FlagSeen,
            Event.FlagLost,
            Event.RecordNow,
            Event.Stop,
            Event.FlagAbsentTimeout,
            Event.CrossingDetected,
            Event.EnterReview,
            Event.ExitReview,
        )

    fun name(s: State): String =
        when (s) {
            is State.Acquisition -> "Acquisition(flag=${if (s.flagVisible) "seen" else "absent"})"
            is State.Review -> "Review(${name(s.underlying)})"
            else -> s.toString()
        }

    fun markdown(): String =
        buildString {
            appendLine("# Session state machine transitions")
            appendLine()
            appendLine("Generated by `TransitionTable.markdown()`. Do not edit by hand.")
            appendLine("`ignored` means the state is unchanged and a `Log` effect is emitted.")
            for (s in states) {
                appendLine()
                appendLine("## ${name(s)}")
                appendLine()
                appendLine("| Event | Next state | Effects |")
                appendLine("|---|---|---|")
                for (e in events) {
                    val t = reduce(s, e)
                    val ignored = t.state == s && t.effects.singleOrNull() is Effect.Log
                    val next = if (ignored) "ignored" else name(t.state)
                    val fx = t.effects.filter { !ignored }.joinToString(", ") { it.toString() }.ifEmpty { "-" }
                    appendLine("| $e | $next | $fx |")
                }
            }
        }
}
